// One-off generator. Run with: node scripts/generate-palettes.js
// Produces 100 named, distinct palettes and prints a TS array literal.
function hsl(h, s, l) {
  h = ((h % 360) + 360) % 360;
  s = Math.max(0, Math.min(100, s));
  l = Math.max(0, Math.min(100, l));
  const c = (1 - Math.abs((2 * l) / 100 - 1)) * (s / 100);
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = l / 100 - c / 2;
  let r = 0, g = 0, b = 0;
  if (h < 60) [r, g, b] = [c, x, 0];
  else if (h < 120) [r, g, b] = [x, c, 0];
  else if (h < 180) [r, g, b] = [0, c, x];
  else if (h < 240) [r, g, b] = [0, x, c];
  else if (h < 300) [r, g, b] = [x, 0, c];
  else [r, g, b] = [c, 0, x];
  const toHex = (v) =>
    Math.round((v + m) * 255)
      .toString(16)
      .padStart(2, "0");
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
}

const hueNames = [
  "Slate", "Teal", "Amber", "Clay", "Indigo", "Mist", "Rose", "Sage",
  "Cobalt", "Coral", "Plum", "Lime", "Cyan", "Ruby", "Olive", "Violet",
  "Sand", "Steel", "Jade", "Copper", "Berry", "Forest", "Sky", "Sunset",
  "Ash", "Onyx", "Pearl", "Ember", "Frost", "Moss", "Lagoon", "Blush",
  "Basalt", "Marigold", "Orchid", "Granite", "Cedar", "Aqua", "Garnet",
  "Sable",
];

const palettes = [];

// Default hand-crafted palette: refined slate + muted teal
palettes.push({
  id: "default",
  name: "Slate Teal",
  light: { accent1: "#0f766e", accent2: "#334155", surface: "#ffffff", bg: "#f8fafc", text: "#1e293b" },
  dark: { accent1: "#14b8a6", accent2: "#94a3b8", surface: "#1e293b", bg: "#0f172a", text: "#e2e8f0" },
});

let i = 0;
while (palettes.length < 100) {
  const hue = (i * 137.508) % 360; // golden angle for even distribution
  const satBase = 35 + (i % 5) * 8; // 35-67
  const name = `${hueNames[i % hueNames.length]} ${hueNames[(i + 7) % hueNames.length]}`;
  const uniqueName = palettes.some((p) => p.name === name) ? `${name} ${i}` : name;

  const accent1 = hsl(hue, satBase + 25, 42);
  const accent2 = hsl(hue + 40, satBase, 35);
  const surfaceL = hsl(hue, 15, 99);
  const bgL = hsl(hue, 20, 97);
  const textL = hsl(hue, 25, 18);

  const accent1D = hsl(hue, satBase + 20, 62);
  const accent2D = hsl(hue + 40, satBase - 5, 65);
  const surfaceD = hsl(hue, 18, 16);
  const bgD = hsl(hue, 22, 9);
  const textD = hsl(hue, 15, 92);

  palettes.push({
    id: `p${i + 1}`,
    name: uniqueName,
    light: { accent1, accent2, surface: surfaceL, bg: bgL, text: textL },
    dark: { accent1: accent1D, accent2: accent2D, surface: surfaceD, bg: bgD, text: textD },
  });
  i++;
}

const body = palettes
  .map(
    (p) => `  {
    id: "${p.id}",
    name: "${p.name}",
    light: { accent1: "${p.light.accent1}", accent2: "${p.light.accent2}", surface: "${p.light.surface}", bg: "${p.light.bg}", text: "${p.light.text}" },
    dark: { accent1: "${p.dark.accent1}", accent2: "${p.dark.accent2}", surface: "${p.dark.surface}", bg: "${p.dark.bg}", text: "${p.dark.text}" },
  }`
  )
  .join(",\n");

const out = `// AUTO-GENERATED by scripts/generate-palettes.js — do not hand-edit token values.
// 100 palettes, each with light/dark token sets: accent1, accent2, surface, bg, text.

export interface PaletteTokens {
  accent1: string;
  accent2: string;
  surface: string;
  bg: string;
  text: string;
}

export interface Palette {
  id: string;
  name: string;
  light: PaletteTokens;
  dark: PaletteTokens;
}

export const palettes: Palette[] = [
${body}
];

export const defaultPalette = palettes[0];

export function getPaletteById(id: string): Palette {
  return palettes.find((p) => p.id === id) ?? defaultPalette;
}
`;

require("fs").writeFileSync(require("path").join(__dirname, "..", "styles", "palettes.ts"), out);
console.log(`Generated ${palettes.length} palettes -> styles/palettes.ts`);
